import java.lang.*;

class A2C {
    public static void main(String args[]) {

        double l = 10, b = 5, h = 5;

        System.out.println("Length: " + l + " units");
        System.out.println("Breadth: " + b + " units");
        System.out.println("Height: " + h + " units");

        System.out.println("Volume of cube: " + (l * l * l) + " unit-cube");

        System.out.println("Volume of cuboid: " + (l * b * h) + " unit-cube");
    }
}